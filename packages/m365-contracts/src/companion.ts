/**
 * Contract for the optional, signed Windows companion. The companion is NOT built in this repository:
 * these types fix the vocabulary (states, capabilities, handshake messages) so the add-in, the backend
 * and a future signed companion agree on names. See docs/WINDOWS_COMPANION_DESIGN.md.
 */
export const M365_COMPANION_CONTRACT_VERSION =
  "2026-10-24.windows-companion.v1" as const;

/** Why the companion can or cannot be used right now. Only "ready" exposes companion features. */
export type CompanionState =
  | "not_installed"
  | "not_signed"
  | "unsupported_host"
  | "version_mismatch"
  | "tenant_not_allowed"
  | "ready";

/** Features that Office.js cannot do and that only a Windows desktop companion could add. */
export type CompanionFeature =
  | "vba-com"
  | "solver"
  | "scenario-manager"
  | "power-pivot-authoring"
  | "data-model-authoring"
  | "olap-pivot-authoring"
  | "sparklines-authoring";

export const COMPANION_FEATURES: readonly CompanionFeature[] = [
  "vba-com",
  "solver",
  "scenario-manager",
  "power-pivot-authoring",
  "data-model-authoring",
  "olap-pivot-authoring",
  "sparklines-authoring",
] as const;

/** The only native operations a signed companion may receive. There is no shell, macro text,
 * arbitrary COM member or Python expression in this protocol. */
export type CompanionOperation =
  | "run-reviewed-vba"
  | "run-solver"
  | "run-scenario-manager"
  | "create-power-pivot-model"
  | "create-data-model"
  | "create-olap-pivot"
  | "create-sparklines";

export type CompanionParameter = string | number | boolean | string[];

export interface CompanionWorkbookBinding {
  /** A per-open-workbook binding generated by the add-in; not a file path or workbook export. */
  sessionId: string;
  workbookFingerprint: string;
  sourceFingerprint: string;
  origin: "excel-desktop-addin";
}

export interface CompanionApprovalGrant {
  approved: true;
  /** Short-lived operation grant, never a Microsoft/Graph bearer token. */
  grantId: string;
  expiresAt: string;
}

export interface CompanionDispatchRequest {
  contractVersion: typeof M365_COMPANION_CONTRACT_VERSION;
  type: "execute";
  requestId: string;
  tenantId: string;
  objectId: string;
  feature: CompanionFeature;
  operation: CompanionOperation;
  workbook: CompanionWorkbookBinding;
  approval: CompanionApprovalGrant;
  /** Bounded operation settings only. Workbook cell values never travel through this contract. */
  parameters: Record<string, CompanionParameter>;
  requestedAt: string;
}

export interface CompanionVerification {
  status: "verified" | "failed";
  changedCells: number;
  evidence: string[];
}

export interface CompanionDispatchResponse {
  contractVersion: typeof M365_COMPANION_CONTRACT_VERSION;
  type: "execute-result";
  requestId: string;
  status: "completed" | "unsupported" | "failed";
  feature: CompanionFeature;
  operation: CompanionOperation;
  workbook: CompanionWorkbookBinding;
  verification: CompanionVerification;
  errorCode?:
    | "UNSUPPORTED_NATIVE_FEATURE"
    | "APPROVAL_INVALID"
    | "WORKBOOK_BINDING_INVALID"
    | "NATIVE_EXECUTION_FAILED";
}

const COMPANION_FEATURE_FOR_OPERATION: Readonly<
  Record<CompanionOperation, CompanionFeature>
> = {
  "run-reviewed-vba": "vba-com",
  "run-solver": "solver",
  "run-scenario-manager": "scenario-manager",
  "create-power-pivot-model": "power-pivot-authoring",
  "create-data-model": "data-model-authoring",
  "create-olap-pivot": "olap-pivot-authoring",
  "create-sparklines": "sparklines-authoring",
};

export function companionFeatureForOperation(
  operation: CompanionOperation,
): CompanionFeature {
  return COMPANION_FEATURE_FOR_OPERATION[operation];
}

/** Pure boundary validation shared by the future signed companion and protocol tests. */
export function isValidCompanionDispatchRequest(
  value: unknown,
): value is CompanionDispatchRequest {
  if (!value || typeof value !== "object") return false;
  const request = value as Partial<CompanionDispatchRequest>;
  if (
    request.contractVersion !== M365_COMPANION_CONTRACT_VERSION ||
    request.type !== "execute" ||
    typeof request.requestId !== "string" ||
    request.requestId.length < 16 ||
    request.requestId.length > 128 ||
    typeof request.tenantId !== "string" ||
    request.tenantId.length < 1 ||
    request.tenantId.length > 128 ||
    typeof request.objectId !== "string" ||
    request.objectId.length < 1 ||
    request.objectId.length > 128 ||
    typeof request.feature !== "string" ||
    !COMPANION_FEATURES.includes(request.feature as CompanionFeature) ||
    typeof request.operation !== "string" ||
    !(request.operation in COMPANION_FEATURE_FOR_OPERATION) ||
    companionFeatureForOperation(request.operation as CompanionOperation) !==
      request.feature ||
    typeof request.requestedAt !== "string"
  )
    return false;
  const workbook = request.workbook;
  if (
    !workbook ||
    workbook.origin !== "excel-desktop-addin" ||
    ![
      workbook.sessionId,
      workbook.workbookFingerprint,
      workbook.sourceFingerprint,
    ].every(
      (part) =>
        typeof part === "string" && part.length >= 16 && part.length <= 256,
    )
  )
    return false;
  const approval = request.approval;
  if (
    !approval ||
    approval.approved !== true ||
    typeof approval.grantId !== "string" ||
    approval.grantId.length < 16 ||
    approval.grantId.length > 256 ||
    typeof approval.expiresAt !== "string"
  )
    return false;
  const parameters = request.parameters;
  if (!parameters || typeof parameters !== "object") return false;
  const entries = Object.entries(parameters);
  if (entries.length > 32) return false;
  try {
    if (JSON.stringify(parameters).length > 16_384) return false;
  } catch {
    return false;
  }
  return entries.every(([key, parameter]) => {
    if (!/^[A-Za-z][A-Za-z0-9_.-]{0,63}$/.test(key)) return false;
    if (/^(?:workbook|cell|row|column|value|token|script|command)/i.test(key))
      return false;
    if (typeof parameter === "string") return parameter.length <= 512;
    if (typeof parameter === "number") return Number.isFinite(parameter);
    if (typeof parameter === "boolean") return true;
    return (
      Array.isArray(parameter) &&
      parameter.length <= 128 &&
      parameter.every((item) => typeof item === "string" && item.length <= 128)
    );
  });
}

/** Pure response validation for the future signed companion boundary. */
export function isValidCompanionDispatchResponse(
  value: unknown,
  request: CompanionDispatchRequest,
): value is CompanionDispatchResponse {
  if (!value || typeof value !== "object") return false;
  const response = value as Partial<CompanionDispatchResponse>;
  const workbook = response.workbook;
  const verification = response.verification;
  if (
    response.contractVersion !== M365_COMPANION_CONTRACT_VERSION ||
    response.type !== "execute-result" ||
    response.requestId !== request.requestId ||
    response.feature !== request.feature ||
    response.operation !== request.operation ||
    !workbook ||
    workbook.origin !== request.workbook.origin ||
    workbook.sessionId !== request.workbook.sessionId ||
    workbook.workbookFingerprint !== request.workbook.workbookFingerprint ||
    workbook.sourceFingerprint !== request.workbook.sourceFingerprint ||
    (response.status !== "completed" &&
      response.status !== "unsupported" &&
      response.status !== "failed") ||
    !verification ||
    (verification.status !== "verified" && verification.status !== "failed") ||
    !Number.isInteger(verification.changedCells) ||
    verification.changedCells < 0 ||
    !Array.isArray(verification.evidence) ||
    verification.evidence.some(
      (evidence) => typeof evidence !== "string" || evidence.length > 500,
    )
  )
    return false;
  if (response.status === "completed" && verification.status !== "verified")
    return false;
  if (response.status !== "completed" && response.errorCode === undefined)
    return false;
  return true;
}

export type CompanionHostPlatform = "web" | "windows" | "mac" | "unknown";
export type CompanionExcelSurface = "web" | "desktop" | "unknown";

/** Authenticated local discovery: the add-in asks, the companion answers. Neither carries workbook data. */
export interface CompanionHelloRequest {
  contractVersion: typeof M365_COMPANION_CONTRACT_VERSION;
  type: "hello";
  /** Fresh random value (at least 16 bytes, base64url) so a reply cannot be replayed. */
  nonce: string;
  /** Tenant id of the signed-in user, checked against the companion's tenant allow-list. */
  tenantId: string;
  /** Oldest companion version the add-in accepts. */
  minCompanionVersion: string;
}

export interface CompanionHelloResponse {
  contractVersion: typeof M365_COMPANION_CONTRACT_VERSION;
  type: "hello-ack";
  /** Echo of the request nonce, covered by the signature. */
  nonce: string;
  companionVersion: string;
  /** Publisher certificate thumbprint (SHA-256) the companion binary is signed with. */
  signerThumbprint: string;
  /** Signature over nonce + companionVersion + tenantId + sorted features, made with the signer key. */
  signature: string;
  /** Result of the companion's own tenant allow-list check for the tenantId in the request. */
  tenantAllowed: boolean;
  features: CompanionFeature[];
  /** Always false by default: raw workbook export is never part of the handshake. */
  rawWorkbookExport: false;
}

/** What the transport reports to the pure state function (no signature maths happens in the pane). */
export type CompanionHandshakeResult =
  | { kind: "no_response" }
  | {
      kind: "response";
      response: CompanionHelloResponse;
      /** True only when a trusted verifier confirmed the signature, nonce echo and publisher pin. */
      signatureVerified: boolean;
    };

export interface CompanionStatusReport {
  contractVersion: typeof M365_COMPANION_CONTRACT_VERSION;
  state: CompanionState;
  reason: string;
  features: CompanionFeature[];
}
